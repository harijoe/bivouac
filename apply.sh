#!/usr/bin/env bash
# bivouac deployment logic, shared by install.sh (first install, SSH update) and the dashboard updater.
# It renders the configuration from /etc/bivouac/bivouac.env, pulls images, recreates the services, waits for the
# new version to be healthy and goes back to the previous version (images, configuration, database) when it is not.
#
#   apply.sh deploy              render + pull + recreate + health check, with automatic rollback (used by install.sh)
#   apply.sh update <version>    switch the installed version to <version>, then deploy (used by the dashboard updater)
#   apply.sh render              only (re)generate the files
#
# Progress is written to $DATA/web/update-status.json, which the dashboard reads.
set -euo pipefail

ETC=/etc/bivouac
OPT=/opt/bivouac
DATA=/var/lib/bivouac
ENV_FILE="$ETC/bivouac.env"
BACKUPS="$DATA/backups"
STATUS="$DATA/web/update-status.json"
KEEP_BACKUPS=3
HEALTH_TIMEOUT="${BIVOUAC_HEALTH_TIMEOUT:-150}"
TRAEFIK_IMAGE="traefik:v3.6"

log()  { printf '\033[1;33m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;31m!!\033[0m  %s\n' "$*" >&2; }

env_get() { sed -n "s/^$1=//p" "$ENV_FILE" | tail -n1; }
env_set() {
  local k="$1" v="$2"
  if grep -q "^$k=" "$ENV_FILE"; then sed -i "s|^$k=.*|$k=$v|" "$ENV_FILE"; else echo "$k=$v" >> "$ENV_FILE"; fi
}

# ---- status file (read by the dashboard; the web container's user owns it)
STEPS=(backup pull configure restart health)
FROM_VERSION=""; TO_VERSION=""; STARTED="$(date -u +%FT%TZ)"
write_status() { # state step error
  local state="$1" step="${2:-}" err="${3:-}"
  [ -d "$DATA/web" ] || return 0
  local tmp="$STATUS.tmp"
  jq -n --arg state "$state" --arg step "$step" --arg err "$err" --arg from "$FROM_VERSION" --arg to "$TO_VERSION" --arg started "$STARTED" \
        --arg finished "$([ "$state" = running ] && echo "" || date -u +%FT%TZ)" --argjson steps "$(printf '%s\n' "${STEPS[@]}" | jq -R . | jq -s .)" \
    '{state:$state, step:$step, steps:$steps, from:$from, to:$to, error:(if $err=="" then null else $err end), startedAt:$started, finishedAt:(if $finished=="" then null else $finished end)}' > "$tmp"
  chown 1000:1000 "$tmp" 2>/dev/null || true
  mv "$tmp" "$STATUS"
}

# ---- files
render() {
  set -a
  while IFS='=' read -r k v; do case "$k" in ''|\#*) ;; *) export "$k=$v";; esac; done < "$ENV_FILE"
  set +a
  DOMAIN="${BIVOUAC_DOMAIN}"
  # docker compose: Traefik (public), web (no Docker access), executor (Docker access, internal only)
ACME_EXTRA=""
[ -z "${BIVOUAC_ACME_EMAIL:-}" ] || ACME_EXTRA="$ACME_EXTRA
      - --certificatesresolvers.le.acme.email=$BIVOUAC_ACME_EMAIL"
[ -z "${BIVOUAC_ACME_STAGING:-}" ] || ACME_EXTRA="$ACME_EXTRA
      - --certificatesresolvers.le.acme.caserver=https://acme-staging-v02.api.letsencrypt.org/directory"
cat > "$OPT/docker-compose.yml" <<EOT
# Generated by install.sh: edit $ENV_FILE instead of this file.
name: bivouac
services:
  traefik:
    image: $TRAEFIK_IMAGE
    container_name: bivouac-traefik
    restart: unless-stopped
    command:
      - --providers.http.endpoint=http://bivouac-web:3001/internal/traefik
      - --providers.http.pollInterval=1s
      - --entrypoints.web.address=:80
      - --entrypoints.web.http.redirections.entrypoint.to=websecure
      - --entrypoints.web.http.redirections.entrypoint.scheme=https
      - --entrypoints.websecure.address=:443
      - --certificatesresolvers.le.acme.httpchallenge=true
      - --certificatesresolvers.le.acme.httpchallenge.entrypoint=web
      - --certificatesresolvers.le.acme.storage=/letsencrypt/acme.json$ACME_EXTRA
      - --log.level=INFO
    ports:
      - "80:80"
      - "443:443"
    volumes:
      - $DATA/traefik:/letsencrypt
    networks: [edge]
  web:
    image: \${BIVOUAC_DAEMON_IMAGE}
    container_name: bivouac-web
    restart: unless-stopped
    user: "1000:1000"
    env_file: $ENV_FILE
    environment:
      - BIVOUAC_DATA_DIR=/data
      - BIVOUAC_PORT=3000
      - BIVOUAC_INTERNAL_PORT=3001
      - BIVOUAC_WEB_HOST=bivouac-web
      - BIVOUAC_EXECUTOR_URL=http://bivouac-executor:3002
      - BIVOUAC_CERT_RESOLVER=le
      - BIVOUAC_PREVIEW_SCHEME=https
    volumes:
      - $DATA/web:/data
    healthcheck:
      test: ["CMD", "curl", "-fsS", "http://127.0.0.1:3000/api/health"]
      interval: 5s
      timeout: 3s
      retries: 20
    networks: [edge, ctl]
  executor:
    image: \${BIVOUAC_DAEMON_IMAGE}
    container_name: bivouac-executor
    restart: unless-stopped
    user: "0:0"
    command: ["node", "packages/daemon/dist/executor-main.js"]
    env_file: $ENV_FILE
    environment:
      - BIVOUAC_DATA_DIR=$DATA
      - BIVOUAC_PORT=3002
      - BIVOUAC_TRAEFIK_CONTAINER=bivouac-traefik
    volumes:
      - /var/run/docker.sock:/var/run/docker.sock
      - $DATA/projects:$DATA/projects
    healthcheck:
      test: ["CMD", "curl", "-fsS", "http://127.0.0.1:3002/health"]
      interval: 5s
      timeout: 3s
      retries: 20
    networks: [ctl, egress]
networks:
  edge: { name: bivouac-edge }
  ctl: { name: bivouac-ctl, internal: true }
  egress: { name: bivouac-egress }
EOT
ln -sf "$ENV_FILE" "$OPT/.env"

cat > /etc/systemd/system/bivouac.service <<EOT
[Unit]
Description=bivouac (Traefik + web + executor via docker compose)
Requires=docker.service
After=docker.service network-online.target
Wants=network-online.target

[Service]
Type=oneshot
RemainAfterExit=yes
WorkingDirectory=$OPT
ExecStart=/usr/bin/docker compose up -d --remove-orphans
ExecStop=/usr/bin/docker compose down
TimeoutStartSec=300

[Install]
WantedBy=multi-user.target
EOT
systemctl daemon-reload

# `bivouac` command (setup link, recovery, test sessions): runs inside the web container
cat > /usr/local/bin/bivouac <<'EOT'
#!/bin/sh
# bivouac admin tool. Usage: sudo bivouac reset-admin | setup-link | status
exec docker exec -i bivouac-web node packages/daemon/dist/cli.js "$@"
EOT
chmod 755 /usr/local/bin/bivouac
}

render_extra() {
  # firewall: task containers must not reach services of this machine (SSH, bivouac internals, Traefik API...)
  cat > "$OPT/firewall.sh" <<'EOT'
#!/usr/bin/env bash
# Managed by bivouac. Task networks use bridges named bvt<id>; whatever they send to this machine is dropped,
# their traffic to other machines (internet) and between their own containers is untouched.
# Also blocks the cloud metadata address (169.254.0.0/16).
set -u
for ipt in iptables ip6tables; do
  command -v "$ipt" >/dev/null 2>&1 || continue
  case "${1:-up}" in
    up)
      "$ipt" -N BIVOUAC-INPUT 2>/dev/null || "$ipt" -F BIVOUAC-INPUT
      "$ipt" -A BIVOUAC-INPUT -m conntrack --ctstate ESTABLISHED,RELATED -j RETURN
      "$ipt" -A BIVOUAC-INPUT -j DROP
      "$ipt" -C INPUT -i 'bvt+' -j BIVOUAC-INPUT 2>/dev/null || "$ipt" -I INPUT 1 -i 'bvt+' -j BIVOUAC-INPUT
      if "$ipt" -nL DOCKER-USER >/dev/null 2>&1; then
        [ "$ipt" = ip6tables ] || { "$ipt" -C DOCKER-USER -i 'bvt+' -d 169.254.0.0/16 -j DROP 2>/dev/null || "$ipt" -I DOCKER-USER 1 -i 'bvt+' -d 169.254.0.0/16 -j DROP; }
      fi ;;
    down)
      while "$ipt" -D INPUT -i 'bvt+' -j BIVOUAC-INPUT 2>/dev/null; do :; done
      "$ipt" -D DOCKER-USER -i 'bvt+' -d 169.254.0.0/16 -j DROP 2>/dev/null
      "$ipt" -F BIVOUAC-INPUT 2>/dev/null; "$ipt" -X BIVOUAC-INPUT 2>/dev/null ;;
  esac
done
exit 0
EOT
  chmod 755 "$OPT/firewall.sh"
  cat > /etc/systemd/system/bivouac-firewall.service <<EOT
[Unit]
Description=bivouac firewall (task containers cannot reach this machine)
Requires=docker.service
After=docker.service
Before=bivouac.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=$OPT/firewall.sh up
ExecStop=$OPT/firewall.sh down

[Install]
WantedBy=multi-user.target
EOT
  systemctl daemon-reload
  systemctl enable bivouac-firewall.service >/dev/null 2>&1 || true
  systemctl restart bivouac-firewall.service
}

# ---- backups: database + configuration, the last $KEEP_BACKUPS are kept
backup() {
  local dir="$BACKUPS/$(date -u +%Y%m%dT%H%M%SZ)"
  mkdir -p "$dir"; chmod 700 "$BACKUPS" "$dir"
  # a graceful stop checkpoints the SQLite WAL, so the copied files are consistent
  docker stop -t 30 bivouac-web >/dev/null 2>&1 || true
  [ -d "$DATA/web" ] && cp -a "$DATA/web" "$dir/web" && rm -f "$dir/web/update-status.json"
  cp -a "$ENV_FILE" "$dir/bivouac.env"
  [ -f "$OPT/docker-compose.yml" ] && cp -a "$OPT/docker-compose.yml" "$dir/docker-compose.yml"
  [ -f /etc/systemd/system/bivouac.service ] && cp -a /etc/systemd/system/bivouac.service "$dir/bivouac.service"
  ls -1d "$BACKUPS"/*/ 2>/dev/null | sort | head -n -"$KEEP_BACKUPS" | xargs -r rm -rf
  echo "$dir"
}

healthy() { # expects the version $1
  [ "$(docker inspect -f '{{.State.Health.Status}}' bivouac-web 2>/dev/null)" = healthy ] &&
  [ "$(docker inspect -f '{{.State.Health.Status}}' bivouac-executor 2>/dev/null)" = healthy ] &&
  [ "$(docker exec bivouac-web printenv BIVOUAC_VERSION 2>/dev/null)" = "$1" ]
}
wait_healthy() {
  local deadline=$((SECONDS + HEALTH_TIMEOUT))
  while [ $SECONDS -lt $deadline ]; do healthy "$1" && return 0; sleep 2; done
  return 1
}

pull_images() {
  local img
  for img in "$(env_get BIVOUAC_DAEMON_IMAGE)" "$(env_get BIVOUAC_TASK_IMAGE)"; do
    docker image inspect "$img" >/dev/null 2>&1 || docker pull -q "$img" >/dev/null || { warn "cannot pull $img"; return 1; }
  done
  docker pull -q "$TRAEFIK_IMAGE" >/dev/null
}

restore() { # $1 = backup dir
  local dir="$1"
  log "Rolling back to the previous version"
  ( cd "$OPT" && docker compose stop web executor ) || true
  cp -a "$dir/bivouac.env" "$ENV_FILE"
  rm -rf "$DATA/web.failed"; mv "$DATA/web" "$DATA/web.failed" 2>/dev/null || true
  cp -a "$dir/web" "$DATA/web"
  [ -f "$dir/docker-compose.yml" ] && cp -a "$dir/docker-compose.yml" "$OPT/docker-compose.yml"
  [ -f "$dir/bivouac.service" ] && cp -a "$dir/bivouac.service" /etc/systemd/system/bivouac.service && systemctl daemon-reload
  ( cd "$OPT" && docker compose up -d --remove-orphans ) || true
  rm -rf "$DATA/web.failed"
}

NEW_VERSION=""
deploy() {
  local target; target="${NEW_VERSION:-$(env_get BIVOUAC_VERSION)}"
  TO_VERSION="$target"
  local previous=0
  docker inspect bivouac-web >/dev/null 2>&1 && previous=1
  if [ "$previous" = 1 ]; then FROM_VERSION="$(docker exec bivouac-web printenv BIVOUAC_VERSION 2>/dev/null || docker inspect -f '{{range .Config.Env}}{{println .}}{{end}}' bivouac-web | sed -n 's/^BIVOUAC_VERSION=//p')"; fi
  write_status running backup
  local bdir=""
  if [ "$previous" = 1 ]; then log "Backing up the database and the configuration"; bdir="$(backup)"; fi
  if [ -n "$NEW_VERSION" ]; then
    # only now: the backup above must hold the configuration of the version that is running
    local registry; registry="$(env_get BIVOUAC_DAEMON_IMAGE)"; registry="${registry%/bivouac-daemon:*}"
    env_set BIVOUAC_VERSION "$NEW_VERSION"
    env_set BIVOUAC_DAEMON_IMAGE "$registry/bivouac-daemon:$NEW_VERSION"
    env_set BIVOUAC_TASK_IMAGE "$registry/bivouac-task:$NEW_VERSION"
  fi
  write_status running pull
  pull_images || { [ "$previous" = 1 ] && { restore "$bdir"; wait_healthy "$FROM_VERSION" || true; write_status rolled_back pull "Could not download the new images. The previous version is running again."; exit 1; }; write_status failed pull "Could not download the images."; exit 1; }
  write_status running configure
  render
  render_extra
  write_status running restart
  log "Starting version $target"
  systemctl enable bivouac.service >/dev/null 2>&1 || true
  ( cd "$OPT" && docker compose up -d --remove-orphans >/dev/null )
  write_status running health
  if wait_healthy "$target"; then
    write_status done health
    log "bivouac $target is running"
    return 0
  fi
  local why="The new version did not become healthy within ${HEALTH_TIMEOUT}s."
  docker logs --tail 20 bivouac-web >&2 2>&1 || true
  if [ "$previous" = 1 ] && [ -n "$bdir" ]; then
    restore "$bdir"
    if wait_healthy "$FROM_VERSION"; then write_status rolled_back health "$why Version $FROM_VERSION is running again, with your data as it was before the update."; else write_status failed health "$why The rollback to $FROM_VERSION did not succeed either: see docker logs bivouac-web."; fi
  else
    write_status failed health "$why"
  fi
  exit 1
}

# keep a log next to the status file, readable after the web service restarts
[ -d "$DATA/web" ] && exec > >(tee -a "$DATA/update.log") 2>&1
case "${1:-}" in
  deploy) deploy ;;
  update)
    new="${2:?usage: apply.sh update <version>}"
    [[ "$new" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo "bad version: $new" >&2; exit 2; }
    NEW_VERSION="$new"
    deploy ;;
  render) render; render_extra ;;
  *) echo "usage: apply.sh deploy | update <version> | render" >&2; exit 2 ;;
esac
